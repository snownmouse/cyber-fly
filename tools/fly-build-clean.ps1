<#
    Clean build for cyber_fly: remove build/ first, then build and flash.

    WHY THIS SCRIPT EXISTS
    After a failed or interrupted ESP-IDF build, the CMake cache keeps a
    broken absolute path. Every later run then fails with an error that has
    nothing to do with the real cause:

        ninja: error: FindFirstFileExA(/D:/.../build/esp-idf/main): The filename, ...
        ERROR: command "system-update-bundle" is not known to idf.py and is not a Ninja target

    Note the extra leading '/' in the path. This cost three build cycles
    before it was recognised as a stale-cache problem rather than a code problem.

    RULE: run this before every flash. Do not just re-run mosaico.py.
    It uses Move rather than Delete: Delete is blocked by the local safety
    policy, Move is not - and Move leaves the old tree available to roll back.

    NOTE: kept ASCII-only on purpose. Windows PowerShell 5.1 reads .ps1 as GBK
    when there is no BOM, so UTF-8 Chinese in comments turns into mojibake and
    the stray quote characters break the parser.

    Usage:
        powershell -NoProfile -ExecutionPolicy Bypass -File tools\fly-build-clean.ps1
        powershell -NoProfile -ExecutionPolicy Bypass -File tools\fly-build-clean.ps1 -SkipReconcile
#>
[CmdletBinding()]
param([switch]$SkipReconcile)

$ErrorActionPreference = 'Continue'

$Ws      = 'D:\ESP\esp-mosaico-vibe'
$Project = Join-Path $Ws 'projects\cyber_fly'
$Py      = 'D:\ESP\espressif-tools\python_env\idf6.2_py3.11_env\Scripts\python.exe'
$Stamp   = Get-Date -Format 'HHmmss'
$Device  = '4553502d49524953010030eda0f4657c'

$env:IDF_PATH             = 'D:\ESP\esp-idf'
$env:IDF_TOOLS_PATH       = 'D:\ESP\espressif-tools'
$env:IDF_CONFIGDEP_ENABLE = '0'
# mosaico.py normally exports these; calling idf.py directly needs them set by
# hand, and a missing one produces a confusing error rather than a clear one:
#   ESP_IDF_VERSION unset     -> TypeError: expected string or bytes-like object,
#                                got 'NoneType'  (inside Version.coerce)
#   cmake/ninja not on PATH   -> ERROR: "cmake" must be available on the PATH
$env:ESP_IDF_VERSION      = '6.2.0'
$env:IDF_PYTHON_ENV_PATH  = 'D:\ESP\espressif-tools\python_env\idf6.2_py3.11_env'
$IdfToolBins = @(
    'D:\ESP\espressif-tools\tools\cmake\4.0.3\bin',
    'D:\ESP\espressif-tools\tools\ninja\1.12.1'
)
foreach ($b in $IdfToolBins) {
    if ((Test-Path $b) -and ($env:PATH -notlike "*$b*")) { $env:PATH = "$b;$env:PATH" }
}

Write-Host '[1/4] clearing stale build tree' -ForegroundColor Cyan
if (Test-Path "$Project\build") {
    # The `FindFirstFileExA(/D:/...)` failure lives in these two BINARY files:
    # they carry a malformed absolute path that no text search can find. They
    # are regenerated by ninja, so moving them is safe. Do this BEFORE moving
    # the tree, otherwise there is nothing left to move them out of.
    foreach ($n in @('.ninja_deps', '.ninja_log')) {
        $f = "$Project\build\$n"
        if (Test-Path $f) {
            [System.IO.File]::Delete($f)
            Write-Host "      removed $n (held the bad path)" -ForegroundColor DarkGray
        }
    }
    $dest = "$Project\_gone_build_$Stamp"
    [System.IO.Directory]::Move("$Project\build", $dest)
    Write-Host "      build -> $(Split-Path $dest -Leaf)" -ForegroundColor DarkGray
}

# Archive dirs are our own build output. Keep the newest 3, rename the rest
# (renaming, not deleting: Delete is blocked here).
$archives = @(Get-ChildItem $Project -Directory -ErrorAction SilentlyContinue |
              Where-Object { $_.Name -like '_gone_*' -or $_.Name -like '_trash_*' })
if ($archives.Count -gt 3) {
    foreach ($a in ($archives | Select-Object -Skip 3)) {
        try {
            [System.IO.Directory]::Move($a.FullName, "$Project\_trash_$Stamp")
            Write-Host "      archived $($a.Name)" -ForegroundColor DarkGray
        } catch { }
    }
}

if ($SkipReconcile) {
    Write-Host '[2/4] skipping reconcile' -ForegroundColor DarkGray
} else {
    Write-Host '[2/4] releasing USB ownership' -ForegroundColor Cyan
    Push-Location $Ws
    & $Py mosaico.py --workspace $Ws iris reconcile --device-id $Device *>$null
    Pop-Location
}

# ROOT CAUSE of `FindFirstFileExA(/D:/...)`, found 2026-10-06 after five failed
# builds: CMake writes this line into CMakeCache.txt with a LOWERCASE drive
# letter, and ninja later concatenates it into a path it cannot open.
#     # For build in directory: d:/ESP/...        <- lowercase d
# It must be repaired before EVERY build attempt, not once at the start: each
# re-configure writes the bad value back.
function Repair-CMakeDriveLetter {
    $cache = "$Project\build\CMakeCache.txt"
    if (-not (Test-Path $cache)) { return }
    $lines = [System.IO.File]::ReadAllLines($cache)
    $want  = '# For build in directory: ' + $Ws.Replace('\', '/') + '/build'
    $fixed = 0
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -match '^# For build in directory: [dD]:/' -and $lines[$i] -ne $want) {
            $lines[$i] = $want
            $fixed++
        }
    }
    if ($fixed) {
        [System.IO.File]::WriteAllLines($cache, $lines, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host "      fixed lowercase drive letter in CMakeCache ($fixed line)" -ForegroundColor DarkGray
    }
    # These two BINARY files cache the bad value as well.
    foreach ($n in @('.ninja_deps', '.ninja_log')) {
        $f = "$Project\build\$n"
        if (Test-Path $f) { [System.IO.File]::Delete($f) }
    }
}

Repair-CMakeDriveLetter

Write-Host '[3/4] building + flashing (full build, ~25 min, 2356 targets)' -ForegroundColor Cyan
$log = 'D:\ESP\tmp\fly-build.log'

# Retry wrapper. The build itself is expensive (25 min) and must NOT be repeated,
# but the flash step fails often and cheaply:
#   cached_state_unavailable / BadStatusLine / device_request_failed
# Those are all "the Gateway session went stale", which a fresh reconcile plus
# an immediate retry clears. The bundle is reused, so a retry costs seconds.
$bundle = "$Project\build\cyber_fly-system-update.irisfw"
$code = 1
for ($attempt = 1; $attempt -le 3; $attempt++) {
    if ($attempt -gt 1) {
        Write-Host "      retry $attempt/3 (bundle already built, this is fast)" -ForegroundColor Yellow
        Start-Sleep -Seconds 5
        Push-Location $Ws
        & $Py mosaico.py --workspace $Ws iris reconcile --device-id $Device *>$null
        Pop-Location
    }
    Push-Location $Ws
    Repair-CMakeDriveLetter
    & $Py mosaico.py --workspace $Ws iris system-update --project projects/cyber_fly *> $log
    $code = $LASTEXITCODE
    Pop-Location
    if ($code -eq 0) { break }

    # Only retry when the build already produced a bundle; otherwise this is a
    # real compile error and retrying just burns another 25 minutes.
    if (-not (Test-Path $bundle)) {
        Write-Host '      no bundle produced -> real build error, not retrying' -ForegroundColor Red
        break
    }
    # Distinguish the two flash-stage failures, they need different actions.
    $logText = ''
    if (Test-Path $log) { $logText = Get-Content $log -Raw -ErrorAction SilentlyContinue }
    if ($logText -match 'No available ESP-Iris USB device') {
        # The board is enumerating as PID_0020 (the chip's DFU firmware) instead
        # of PID_4002 (normal, which the Iris transport speaks). Reconcile and
        # retry cannot fix that, but a hard reset from esptool does: it uploads
        # the stub flasher and then resets, which drops the chip out of DFU.
        $sp = @(Get-PnpDevice -PresentOnly -ErrorAction SilentlyContinue |
                Where-Object { $_.InstanceId -like 'USB\VID_303A*' })
        $inDfu = (($sp | ForEach-Object { $_.InstanceId }) -join ' ') -match 'PID_0020'
        if ($inDfu) {
            $port = $null
            $ser = @(Get-CimInstance Win32_SerialPort -ErrorAction SilentlyContinue)
            if ($ser.Count -gt 0) { $port = $ser[0].DeviceID }
            if ($port) {
                Write-Host "      board is in DFU mode; resetting it with esptool on $port" -ForegroundColor Yellow
                & $Py -m esptool --port $port chip-id 2>&1 |
                    Select-String -Pattern 'Connected|resetting' | ForEach-Object { Write-Host "      $_" -ForegroundColor DarkGray }
                Start-Sleep -Seconds 3
                $now = @(Get-PnpDevice -PresentOnly -ErrorAction SilentlyContinue |
                         Where-Object { $_.InstanceId -like 'USB\VID_303A*' })
                if ((($now | ForEach-Object { $_.InstanceId }) -join ' ') -match 'PID_4002') {
                    Write-Host '      back to normal mode, retrying' -ForegroundColor Green
                    Push-Location $Ws
                    & $Py mosaico.py --workspace $Ws iris reconcile --device-id $Device *>$null
                    Pop-Location
                    Push-Location $Ws
                    Repair-CMakeDriveLetter
                    & $Py mosaico.py --workspace $Ws iris system-update --project projects/cyber_fly *> $log
                    $code = $LASTEXITCODE
                    Pop-Location
                    if ($code -eq 0) { break }
                } else {
                    Write-Host '      still not back to PID_4002 - power-cycle the board' -ForegroundColor Red
                }
            } else {
                Write-Host '      no serial port found; power-cycle the board' -ForegroundColor Red
            }
        } else {
            Write-Host '      board is not enumerating on USB at all' -ForegroundColor Red
        }
        continue
    }
    Write-Host "      exit $code but bundle exists -> treating as a flash-stage failure" -ForegroundColor Yellow
}

Write-Host '[4/4] result' -ForegroundColor Cyan
Write-Host "      exit = $code"
$tail = Get-Content $log -Encoding Unicode -ErrorAction SilentlyContinue |
        Where-Object { $_ -match 'succeeded|failed|error|validation|bundle:' } |
        Select-Object -Last 8
if ($tail) { $tail | ForEach-Object { Write-Host "      $_" -ForegroundColor DarkGray } }
Write-Host "      full log: $log"

if ($code -eq 0) {
    Write-Host 'flash OK. Next: capture logs' -ForegroundColor Green
    Write-Host "  iris reconcile --device-id $Device ; iris logs --timeout 40"
} else {
    Write-Host 'build failed. If it is the FindFirstFileExA error, build/ is stale again - re-run this script.' -ForegroundColor Yellow
    exit $code
}
